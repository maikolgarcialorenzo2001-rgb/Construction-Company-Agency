/** The demo defaults for an id outside the registry. */
const DEFAULT_SECTOR = 'Demo';

/** Bare digits of a phone number: the WhatsApp deep link carries digits only. */
const toDigits = (phone: string): string => phone.replace(/\D/g, '');

/** A company profile carries `companyId`; a worker profile carries `userId`. */
const isCompanyProfile = (
  profile: WorkerProfile | CompanyProfile
): profile is CompanyProfile => 'companyId' in profile;

/**
 * The initials of a display name: the first letter of the first two words,
 * uppercased and without a separator (`"Lucía Fernández"` → `LF`). A single
 * word yields a single letter.
 */
const initialsFor = (displayName: string): string =>
  displayName
    .trim()
    .split(/\s+/)
    .filter((word) => word.length > 0)
    .slice(0, 2)
    .map((word) => word.charAt(0).toUpperCase())
    .join('');

/**
 * A deterministic avatar color: the sum of the id's char codes picks an index in
 * the literal class pairs. The same id always maps to the same color, on every
 * machine and in every session.
 */
const avatarColorFor = (id: string): string => {
  let hash = 0;
  for (const char of id) {
    hash = (hash + char.charCodeAt(0)) % AVATAR_COLOR_CLASSES.length;
  }
  return AVATAR_COLOR_CLASSES[hash];
};

/** The extras of a profile: the seeded ones, or the demo defaults. */
const extrasFor = (id: string, phone: string): ProfileExtras => {
  const seeded = PROFILE_EXTRAS[id];
  if (seeded) {
    return seeded;
  }
  const digits = toDigits(phone);
  return {
    sector: DEFAULT_SECTOR,
    verified: false,
    whatsapp: digits === '' ? '' : `+${digits}`,
    followerCount: 0,
    followingCount: 0
  };
};

/**
 * Maps a contract-shaped profile into the demo-only `ProfileView`. The contract
 * profile is never mutated: the mapper only reads it.
 */
export const profileViewFor = (profile: WorkerProfile | CompanyProfile): ProfileView => {
  if (isCompanyProfile(profile)) {
    const extras = extrasFor(profile.companyId, profile.phone ?? '');
    return {
      id: profile.companyId,
      role: profile.role,
      displayName: profile.name,
      initials: initialsFor(profile.name),
      avatarColor: avatarColorFor(profile.companyId),
      sector: extras.sector,
      verified: extras.verified,
      bio: profile.description ?? '',
      location: profile.location ?? '',
      createdAt: profile.createdAt,
      phone: profile.phone ?? '',
      whatsapp: extras.whatsapp,
      contactEmail: profile.contactEmail ?? '',
      website: profile.website ?? '',
      skills: [],
      followerCount: extras.followerCount,
      followingCount: extras.followingCount
    };
  }

  const extras = extrasFor(profile.userId, profile.phone ?? '');
  return {
    id: profile.userId,
    role: profile.role,
    displayName: profile.fullName,
    initials: initialsFor(profile.fullName),
    avatarColor: avatarColorFor(profile.userId),
    sector: extras.sector,
    verified: extras.verified,
    bio: profile.bio ?? '',
    location: profile.location ?? '',
    createdAt: profile.createdAt,
    phone: profile.phone ?? '',
    whatsapp: extras.whatsapp,
    contactEmail: '',
    website: '',
    skills: profile.skills ?? [],
    followerCount: extras.followerCount,
    followingCount: extras.followingCount
  };
};
